static uint16_t crc(const uint8_t *p, unsigned n)
{
	uint16_t c = 0;
	while (n--) {
		c ^= (uint16_t)*p++ << 8;
		for (unsigned b = 0; b < 8; b++)
			c = (uint16_t)((c << 1) ^ ((c & 0x8000) ? 0x1021 : 0));
	}
	return (uint16_t)~c;
}
static bool name_decode(const uint8_t *p, unsigned n, char name[15])
{
	uint16_t w = (uint16_t)(0xC433 + 586 * (n / 2 - 1));
	uint8_t high = 0;
	bool ended = false;
	memset(name, 0, 15);
	for (unsigned j = 0; j < n; j++) {
		uint8_t odd = (uint8_t)w | 1, inv = 1;
		// Newton iteration doubles the correct inverse bits each step.
		for (unsigned k = 0; k < 3; k++)
			inv = (uint8_t)(inv * (2 - odd * inv));
		uint8_t ch = (uint8_t)(inv * (subst[p[j]] - (uint8_t)(w >> 8)));
		w = (uint16_t)(w + 293 * ((unsigned)p[j] + 1));
		if (!(j & 1)) { high = ch; continue; }
		if (high || (ch && (ch < 0x20 || ch > 0x7e)) || (ended && ch))
			return false;
		if (!ch) ended = true;
		if (j / 2 < 14) name[j / 2] = (char)ch;
	}
	return true;
}
bool p25_alias90_lc(p25_alias90_t *a, const uint8_t raw[9], uint32_t src, uint16_t tg,
		    char name[15], uint32_t *recovered_src)
{
	if (raw[1] != 0x90 || (raw[0] != 0x15 && raw[0] != 0x17))
		return false;
	a->result = P25_ALIAS90_WAIT;
	if (raw[0] == 0x15) {
		uint16_t group = (uint16_t)(raw[2] << 8 | raw[3]);
		if (!raw[4] || raw[4] > 16 || raw[5] != 1 || !group || (tg && group != tg)) {
			memset(a, 0, sizeof *a);
			a->result = P25_ALIAS90_BAD_HEADER;
			return false;
		}
		if (a->count != raw[4] || a->seq != raw[7] >> 4 || a->tg != group)
			memset(a, 0, sizeof *a);
		a->count = raw[4]; a->seq = raw[7] >> 4; a->tg = group;
		return false;
	}
	unsigned block = raw[2];
	if (!a->count) {
		a->result = P25_ALIAS90_NO_HEADER;
		return false;
	}
	if (!block || block > a->count || raw[3] >> 4 != a->seq || (tg && tg != a->tg)) {
		a->result = P25_ALIAS90_BAD_BLOCK;
		return false;
	}
	for (unsigned k = 0; k < 44; k++) {
		unsigned from = k + 28, to = (block - 1) * 44 + k;
		uint8_t mask = (uint8_t)(1u << (7 - to % 8));
		a->data[to / 8] = (uint8_t)((a->data[to / 8] & ~mask) |
			(((raw[from / 8] >> (7 - from % 8)) & 1) ? mask : 0));
	}
	a->seen |= (uint16_t)(1u << (block - 1));
	if (a->seen != (uint16_t)((1u << a->count) - 1)) return false;
	unsigned bytes = (a->count * 44 + 7) / 8;
	uint32_t rid = (uint32_t)a->data[4] << 16 | (uint32_t)a->data[5] << 8 | a->data[6];
	if (!rid || (src && rid != src)) {
		a->result = P25_ALIAS90_WRONG_SOURCE;
		return false;
	}
	// Accept only complete, checksum-validated text, never a best-effort name.
	a->result = P25_ALIAS90_BAD_CRC;
	for (unsigned n = 2; n + 9 <= bytes; n += 2) {
		unsigned end = 7 + n;
		if (crc(a->data, end) != (uint16_t)(a->data[end] << 8 | a->data[end + 1])) continue;
		a->result = P25_ALIAS90_BAD_TEXT;
		bool pad = true;
		for (unsigned k = end + 2; k < bytes; k++)
			if (a->data[k]) pad = false;
		if (pad && name_decode(a->data + 7, n, name)) {
			*recovered_src = rid;
			a->result = P25_ALIAS90_COMPLETE;
			return true;
		}
	}
	return false;
}
