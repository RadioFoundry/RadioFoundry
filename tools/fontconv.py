"""Convert a fixed-cell BDF bitmap font into the C data the UI draws with (core/ui/font.h).

    tools/fontconv.py FONT.bdf NAME LICENSE_FILE SPDX_ID > core/ui/fonts/NAME.inc

Output: one `static const uint8_t NAME_bits[]` array, glyphs in the order 0x20..0x7E then the extra code points
below, each glyph `height` rows of `ceil(width / 8)` bytes, MSB = leftmost pixel. Glyphs the font lacks are all
zero and their bit is set in `NAME_MISSING` (the UI then draws a fallback). The font's own copyright comment and
license text are carried into the header of the generated file.
"""
import sys

# Extra glyphs after ASCII, in slot order (core/ui/font.h GLYPH_*)
EXTRAS = [0x2026, 0x00B7, 0x2192, 0x00B0]


def parse(path):
    props = {}
    comments = []
    glyphs = {}
    with open(path, encoding="ascii", errors="replace") as f:
        lines = f.read().splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("COMMENT"):
            comments.append(line[8:] if len(line) > 8 else "")
        elif line.startswith("FONTBOUNDINGBOX"):
            props["bbx"] = [int(v) for v in line.split()[1:5]]
        elif line.startswith("FONT_ASCENT"):
            props["ascent"] = int(line.split()[1])
        elif line.startswith("FONT_DESCENT"):
            props["descent"] = int(line.split()[1])
        elif line.startswith("STARTCHAR"):
            enc = None
            bbx = None
            rows = []
            i += 1
            while not lines[i].startswith("ENDCHAR"):
                l = lines[i]
                if l.startswith("ENCODING"):
                    enc = int(l.split()[1])
                elif l.startswith("BBX"):
                    bbx = [int(v) for v in l.split()[1:5]]
                elif l.startswith("BITMAP"):
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        rows.append(lines[i].strip())
                        i += 1
                    break
                i += 1
            if enc is not None and bbx is not None:
                glyphs[enc] = (bbx, rows)
        i += 1
    return props, comments, glyphs


def render(props, glyph):
    cw, ch = props["bbx"][0], props["bbx"][1]
    ascent = props["ascent"]
    (gw, gh, gx, gy), rows = glyph
    cell = [[0] * cw for _ in range(ch)]
    top = ascent - (gy + gh)
    for r, hexrow in enumerate(rows[:gh]):
        bits = int(hexrow, 16) if hexrow else 0
        nbits = len(hexrow) * 4
        for c in range(gw):
            if bits >> (nbits - 1 - c) & 1:
                y, x = top + r, gx + c
                if 0 <= y < ch and 0 <= x < cw:
                    cell[y][x] = 1
    stride = (cw + 7) // 8
    out = []
    for y in range(ch):
        for b in range(stride):
            v = 0
            for k in range(8):
                x = b * 8 + k
                if x < cw and cell[y][x]:
                    v |= 0x80 >> k
            out.append(v)
    return out


def main():
    if len(sys.argv) != 5:
        sys.stderr.write(__doc__)
        return 2
    path, name, license_path, spdx = sys.argv[1:5]
    props, comments, glyphs = parse(path)
    cw, ch = props["bbx"][0], props["bbx"][1]
    with open(license_path, encoding="utf-8") as f:
        license_text = f.read().strip().splitlines()

    codes = list(range(0x20, 0x7F)) + EXTRAS
    missing = 0
    data = []
    for slot, code in enumerate(codes):
        if code in glyphs:
            data.append(render(props, glyphs[code]))
        else:
            if code < 0x7F:
                raise SystemExit("font lacks ASCII 0x%02X" % code)
            missing |= 1 << (slot - 95)
            data.append([0] * (((cw + 7) // 8) * ch))

    w = sys.stdout.write
    w("// SPDX-License-Identifier: %s\n" % spdx)
    for c in comments:
        c = c.strip().lstrip("/*").rstrip("*/").strip()
        if c.startswith("*"):
            c = c[1:].strip()
        if c.startswith("Copyright"):
            w("// SPDX-FileCopyrightText: %s\n" % c[len("Copyright"):].strip(" (c)"))
    w("//\n// Generated by tools/fontconv.py from %s. Do not edit.\n" % path.rsplit("/", 1)[-1])
    w("// Original header:\n")
    for c in comments:
        w("//   %s\n" % c.rstrip())
    w("//\n// License of the font data:\n//\n")
    for l in license_text:
        w(("//   %s" % l).rstrip() + "\n")
    w("\n")
    w("#define %s_W %d\n#define %s_H %d\n#define %s_ASCENT %d\n#define %s_MISSING 0x%02Xu\n\n"
      % (name.upper(), cw, name.upper(), ch, name.upper(), props["ascent"], name.upper(), missing))
    w("static const uint8_t %s_bits[] = {\n" % name)
    for slot, (code, g) in enumerate(zip(codes, data)):
        label = chr(code) if 0x20 < code < 0x7F and chr(code) not in "\\" else "U+%04X" % code
        w("\t" + ",".join("0x%02X" % v for v in g) + ",\t// %s\n" % label)
    w("};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
