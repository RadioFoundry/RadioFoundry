"""Generate the optional fixed-cell Latin extension from the existing font families."""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

from fontconv import pack, parse, render
from i18n import EXTENDED_LATIN


# Turkish letters without usable 5x8 Spleen bitmaps, drawn in the same grid.
TINY = (
    (0x50, 0x20, 0x70, 0x80, 0xB0, 0x90, 0x70, 0),
    (0x50, 0x20, 0, 0x70, 0x90, 0x70, 0x10, 0x60),
    (0x20, 0, 0x70, 0x20, 0x20, 0x20, 0x70, 0),
    (0, 0, 0, 0x60, 0x20, 0x20, 0x70, 0),
    (0x70, 0x80, 0x60, 0x10, 0xE0, 0x20, 0x40, 0),
    (0, 0, 0x70, 0xC0, 0x30, 0xE0, 0x20, 0x40),
    (0x70, 0x80, 0x80, 0x80, 0x70, 0x20, 0x40, 0),
    (0, 0, 0x70, 0x80, 0x80, 0x70, 0x20, 0x40),
    (0x50, 0, 0x60, 0x90, 0x90, 0x90, 0x60, 0),
    (0, 0x50, 0, 0x60, 0x90, 0x90, 0x60, 0),
    (0x50, 0, 0x90, 0x90, 0x90, 0x90, 0x60, 0),
    (0, 0x50, 0, 0x90, 0x90, 0x90, 0x70, 0),
)


def from_outline(font, char, width, height, ascent, bpp):
    # Keep the whole mark before positioning the ink in the destination cell.
    image = Image.new("L", (width, 3 * height))
    ImageDraw.Draw(image).text((0, height + ascent), char, font=font, fill=255, anchor="ls")
    pixels = [[image.getpixel((x, y)) for x in range(width)] for y in range(image.height)]
    if bpp == 1:
        pixels = [[int(value >= 128) for value in row] for row in pixels]
    else:
        pixels = [[(3 * value + 127) // 255 for value in row] for row in pixels]
    ink = [y for y, row in enumerate(pixels) if any(row)]
    if not ink or ink[-1] - ink[0] >= height:
        raise ValueError(f"U+{ord(char):04X} does not fit {width}x{height} at {bpp} bpp")
    cropped = pixels[ink[0]:ink[-1] + 1]
    top = min(max(ink[0] - height, 0), height - len(cropped))
    cell = [[0] * width for _ in range(height)]
    cell[top:top + len(cropped)] = cropped
    return pack(cell, bpp)


def emit(name, glyphs):
    lines = [f"static const uint8_t {name}[] = {{"]
    for glyph in glyphs:
        lines.append("\t" + ", ".join(f"0x{byte:02x}" for byte in glyph) + ",")
    return lines + ["};", ""]


def header(spdx, upstream, license_path):
    return [f"// SPDX-License-Identifier: {spdx}", f"// Source: {upstream}",
            "// Generated by tools/latinfont.py.", "//",
            *(("// " + line).rstrip() for line in license_path.read_text(encoding="utf-8").splitlines()),
            ""]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("spleen", type=Path, help="Spleen 2.1.0 source directory")
    ap.add_argument("jbmono", type=Path, help="JetBrains Mono v2.304 source directory")
    ap.add_argument("output", type=Path)
    args = ap.parse_args()

    spleen = header("BSD-2-Clause", "https://github.com/fcambus/spleen/tree/2.1.0", args.spleen / "LICENSE")
    spleen += emit("spleen_5x8_extended", TINY[:len(EXTENDED_LATIN)])
    spleen += emit("spleen_5x8_turkish_latin1", TINY[len(EXTENDED_LATIN):])
    spleen.append("#if !CONFIG_FONT_AA || defined(FONT_BOTH)")
    for size in ("8x16", "12x24", "16x32"):
        props, _, shapes = parse(args.spleen / f"spleen-{size}.bdf")
        if size == "16x32":
            spleen.append("#if CONFIG_FONT_XL")
        spleen += emit(f"spleen_{size}_extended", [render(props, shapes[ord(char)]) for char in EXTENDED_LATIN])
        if size == "16x32":
            spleen.append("#endif")
    spleen.extend(["#endif", ""])
    (args.output / "latin_extended_spleen.inc").write_bytes("\n".join(spleen).encode("utf-8"))

    mono = header("OFL-1.1", "https://github.com/JetBrains/JetBrainsMono/tree/v2.304", args.jbmono / "OFL.txt")
    path = args.jbmono / "fonts/ttf/JetBrainsMono-Bold.ttf"
    probe = ImageFont.truetype(str(path), 100).getlength("0")
    mono.append("#if !CONFIG_FONT_AA || defined(FONT_BOTH)")
    six = ImageFont.truetype(str(path), 600 / probe)
    mono += emit("spleen_6x12_extended", [from_outline(six, char, 6, 12, 9, 1) for char in EXTENDED_LATIN])
    mono.extend(["#endif", "#if CONFIG_FONT_AA"])
    for width, height, ascent, switch in ((6, 12, 9, ""), (8, 16, 12, ""), (9, 18, 14, "CONFIG_FONT_BIG"),
                                          (12, 24, 19, ""), (16, 32, 26, "CONFIG_FONT_XL")):
        font = ImageFont.truetype(str(path), 100 * width / probe)
        if switch:
            mono.append("#if " + switch)
        mono += emit(f"jbmono_{width}x{height}_extended",
                     [from_outline(font, char, width, height, ascent, 2) for char in EXTENDED_LATIN])
        if switch:
            mono.append("#endif")
    mono.extend(["#endif", ""])
    (args.output / "latin_extended_jbmono.inc").write_bytes("\n".join(mono).encode("utf-8"))


if __name__ == "__main__":
    main()
