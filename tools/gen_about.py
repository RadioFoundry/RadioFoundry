"""Write the About page's data header from AUTHORS and a platform's THIRD_PARTY list (run by make).

    gen_about.py AUTHORS platform/<platform>/THIRD_PARTY OUT.h

AUTHORS: one author per line, "Name [CALLSIGN] <email>"; the email is not shown on the radio. THIRD_PARTY: one
"component: license" per line; lines starting with # are comments. OUT.h is rewritten only when its content changes, so builds
don't redo work for nothing; it prints "changed" when it was rewritten.
"""
import os
import re
import sys


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lines(path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                yield line


def main():
    authors_path, third_path, out = sys.argv[1:4]
    authors = [re.sub(r"\s*<[^>]*>", "", a).strip() for a in lines(authors_path)]
    third = []
    for t in lines(third_path):
        name, _, lic = t.partition(":")
        third.append((name.strip(), lic.strip()))
    text = ["// Generated by tools/gen_about.py from AUTHORS and %s; do not edit" % third_path,
            "#define ODR_ABOUT_AUTHORS { %s }" % ", ".join(c_str(a[:35]) for a in authors),
            "#define ODR_ABOUT_AUTHOR_COUNT %d" % len(authors),
            "#define ODR_ABOUT_THIRD_PARTY { %s }" % ", ".join("{ %s, %s }" % (c_str(n[:35]), c_str(l[:19]))
                                                               for n, l in third),
            "#define ODR_ABOUT_THIRD_PARTY_COUNT %d" % len(third), ""]
    text = "\n".join(text)
    try:
        with open(out, encoding="utf-8") as f:
            if f.read() == text:
                return 0
    except OSError:
        pass
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    print("changed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
